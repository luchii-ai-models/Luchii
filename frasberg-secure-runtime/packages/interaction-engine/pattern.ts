export function buildPattern(exchange: any) {
  return {
    structuralPattern: exchange.influenceExchange.fieldPropagation.vectorInfluence.forceDirection.dynamicsVector.motionForce.travelKinetics.navigationMotion.routeDecision.pathNavigation.directionMap.pathwayDirection.structuralPathway === "open" ? "connected" : "disconnected",
    harmonyPattern: exchange.interactionExchange.harmonyInteraction === "stable" ? "coherent" : "chaotic",
    checksum: Math.random().toString(36).slice(2)
  };
}
