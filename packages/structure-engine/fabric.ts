export function buildFabric(architecture: any) {
  return {
    structuralFabric: architecture.patternArchitecture.exchangeStructure.interactionFlow.influenceExchange.fieldPropagation.vectorInfluence.forceDirection.dynamicsVector.motionForce.travelKinetics.navigationMotion.routeDecision.pathNavigation.directionMap.pathwayDirection.structuralPathway === "open" ? "woven" : "loose",
    harmonyFabric: architecture.formationArchitecture.harmonyFormation === "coherent" ? "stable" : "unstable",
    checksum: Math.random().toString(36).slice(2)
  };
}
